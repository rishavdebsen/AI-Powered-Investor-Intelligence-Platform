SAMPLE_DIR = Path(__file__).resolve().parent / "data" / "sample"

KPI_CARDS = [
    ("revenue", "Revenue", "Top-line sales for the fiscal year"),
    ("net_income", "Net Income", "Profit after all expenses and tax"),
    ("operating_income", "Operating Income", "Profit from core operations"),
    ("operating_cash_flow", "Operating Cash Flow", "Cash generated by operations"),
    ("total_assets", "Total Assets", "Everything the company owns"),
    ("total_liabilities", "Total Liabilities", "Everything the company owes"),
]
COMPANY_COLORS = ["#5B8DEF", "#E8A33D", "#3FB68B", "#C65B7C", "#8D6FD1", "#4FA3A5"]
UNIT_SCALE = {"billion": 1.0, "million": 0.001, "thousand": 0.000001, "": 1.0}
UNIT_SUFFIX = {"billion": "B", "million": "M", "thousand": "K", "": ""}


def new_service(session_id: str) -> InvestorIntelService:
    """One isolated service per visitor session: samples pre-load into a
    per-session SQLite file, and uploads land in that same session's store.
    Nothing is shared across anonymous visitors, and nothing resets while a
    session keeps interacting (reruns reuse st.session_state)."""
    settings = get_settings()
    uploads = Path(settings.data_dir) / "uploads"
    uploads.mkdir(parents=True, exist_ok=True)
    service = InvestorIntelService(settings, database_url=f"sqlite:///{uploads}/session-{session_id}.db")
    for filing in sorted(SAMPLE_DIR.glob("*.md")):
        service.ingest(filing)  # pre-load the bundled fictional sample filings
    return service


@st.cache_resource
def cleanup_orphan_uploads() -> None:
    """Runs once per app process, before the first session store is created.
    Leftover upload/session files from dead sessions are removed here, never
    during an active session, so no file in use is ever deleted."""
    uploads = Path(get_settings().data_dir) / "uploads"
    if uploads.exists():
        for leftover in uploads.iterdir():
            if leftover.is_file():
                leftover.unlink(missing_ok=True)


if "session_id" not in st.session_state:
    st.session_state.session_id = uuid4().hex[:12]
if "service" not in st.session_state:
    cleanup_orphan_uploads()
    st.session_state.service = new_service(st.session_state.session_id)


def company_label(doc_name: str) -> tuple[str, str]:
    """Split a filing filename into (company, fiscal-year label)."""
    stem = Path(doc_name).stem
    stem = re.sub(r"^[0-9a-f]{12}-", "", stem)  # strip upload session prefix
    m = re.search(r"(?i)^(.*?)[-_ ]?fy[-_ ]?(\d{4})$", stem)
    if m:
        company = re.sub(r"[-_]+", " ", m.group(1)).strip().title()
        return company or stem, f"FY{m.group(2)}"
    return re.sub(r"[-_]+", " ", stem).strip().title(), ""


def money(value: str, unit: str) -> str:
    return f"${value}{UNIT_SUFFIX.get(unit, '')}"


def scaled(value: str, unit: str) -> float:
    try:
        return float(value.replace(",", "")) * UNIT_SCALE.get(unit, 1.0)
    except ValueError:
        return 0.0


def initials(company: str) -> str:
    words = [w for w in company.split() if w]
    return ("".join(w[0] for w in words)[:2]).upper() or "CO"


def section_text(service: InvestorIntelService, doc_id: str, heading: str) -> str:
    with service._session_factory() as session:
        rows = session.query(ChunkRow).filter_by(doc_id=doc_id, heading=heading).all()
    return "\n\n".join(r.text for r in rows if r.text).strip()


