"""Standalone Streamlit dashboard demo (e.g. Streamlit Community Cloud).

Runs the platform in-process with the local TF-IDF retrieval profile - no
separate FastAPI server and no API keys required. The reviewed deployment
remains the FastAPI + Streamlit split described in the README; this additive
entrypoint demos the project as a single free Streamlit app.

Honesty notes: the bundled sample filings describe three fictional companies
with synthetic figures, and answers are extractive snippets from ingested
filings (local TF-IDF retrieval), not generative AI. The UI labels both.
"""
