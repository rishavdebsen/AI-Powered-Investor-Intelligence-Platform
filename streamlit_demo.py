main_col, chat_col = st.columns([2.3, 1.0], gap="large")

with main_col:
    # ---- KPI comparison cards ----------------------------------------------
    for row_start in range(0, len(KPI_CARDS), 3):
        cols = st.columns(3)
        for col, (kpi_name, title, subtitle) in zip(cols, KPI_CARDS[row_start : row_start + 3]):
            entries = kpi_map.get(kpi_name, {})
            max_val = max((scaled(e["value"], e["unit"]) for e in entries.values()), default=0.0)
            rows_html = ""
            for doc_id in doc_order:
                entry = entries.get(doc_id)
                if not entry:
                    continue
                company, year = company_label(doc_ids[doc_id])
                color = colors[doc_id]
                width = int(round(100 * scaled(entry["value"], entry["unit"]) / max_val)) if max_val else 0
                rows_html += (
                    "<div class='kpi-row'>"
                    f"<div class='kpi-badge' style='background:{color};'>{html.escape(initials(company))}</div>"
                    f"<div class='kpi-name'>{html.escape(company)}<br/><span style='color:#7d8590; font-size:11px;'>{html.escape(year)}</span></div>"
                    f"<div class='kpi-val'>{html.escape(money(entry['value'], entry['unit']))}</div>"
                    "</div>"
                    f"<div class='kpi-bar' style='background:{color}; width:{max(width, 6)}%;'></div>"
                )
            if not rows_html:
                rows_html = "<div class='kpi-sub'>No data extracted yet.</div>"
            col.markdown(
                f"<div class='kpi-card'><p class='kpi-title'>{title}</p>"
                f"<p class='kpi-sub'>{subtitle}</p>{rows_html}</div>",
                unsafe_allow_html=True,
            )

