doc_order = [d["doc_id"] for d in docs]
colors = {doc_id: COMPANY_COLORS[i % len(COMPANY_COLORS)] for i, doc_id in enumerate(doc_order)}
kpis = service.list_kpis()
kpi_map: dict[str, dict[str, dict]] = {}
for row in kpis:
    kpi_map.setdefault(row["name"], {})[row["doc_id"]] = row

